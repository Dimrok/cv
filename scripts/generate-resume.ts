/**
 * Renders the resume data (src/data) as Markdown and LaTeX, so the website, the
 * Markdown and the PDF versions never drift apart.
 *
 * Usage: yarn resume:generate
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { education } from '../src/data/education'
import { experience } from '../src/data/experience'
import { projects } from '../src/data/projects'
import { self } from '../src/data/self'
import { formatPeriod, periodDuration } from '../src/lib/period'
import messages from '../src/localization/en-EN'
import type { Period } from '../src/types/experience'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const MARKDOWN_PATH = resolve(ROOT, 'resume/resume.md')
const LATEX_PATH = resolve(ROOT, 'resume/latex/resume.tex')

const fullName = `${self.firstName} ${self.lastName}`
const age = self.birth.diffNow().negate().toFormat('y')
const nationality = messages.nationality.fr
const skillNames = self.skills.map((skill) => `${skill.name}${skill.stale ? '*' : ''}`)
const staleSkillsNote = self.skills.some((skill) => skill.stale)
  ? `* ${messages.skills.stale}`
  : undefined
const interests = (keys: typeof self.professionalInterests) =>
  keys.map((key) => messages.interests[key]).join(', ')

function period(dates: Period, format?: string): string {
  return `${formatPeriod(dates, format)} (${periodDuration(dates)})`
}

function renderMarkdown(): string {
  const lines: string[] = []
  const push = (...values: string[]) => lines.push(...values)

  push(`# ${fullName}`, '', `**${self.headline}**`, '')
  push(
    `${self.locations.join(' | ')} · ${nationality} · ${age} years old`,
    '',
    [
      self.phone.label,
      ...[self.email, ...self.links].map((link) => `[${link.label}](${link.href})`),
    ].join(' · '),
    '',
    self.summary,
    '',
  )

  push('## Experience', '')
  for (const xp of experience) {
    push(`### ${xp.company} — ${xp.title}`, '', `*${period(xp.dates)} · ${xp.location}*`, '')
    push(`> ${xp.about}`, '')
    for (const stage of xp.stages.filter((stage) => !stage.hide)) {
      push(`#### ${stage.name}`, '', `*${period(stage.dates)}*`, '')
      if (stage.description) push(stage.description, '')
      push(`**Stack:** ${stage.skills.join(', ')}`, '')
      push(...stage.tasks.map((task) => `- ${task}`), '')
    }
  }

  push('## Personal Projects', '')
  for (const project of projects) {
    const title = project.url ? `[${project.name}](${project.url})` : project.name
    push(`### ${title}`, '', `*${period(project.dates)}*`, '', project.about, '')
    push(`**Stack:** ${project.skills.join(', ')}`, '')
    push(...project.tasks.map((task) => `- ${task}`), '')
  }

  push('## Education', '')
  for (const edu of education) {
    push(`### ${edu.institution} — ${edu.degree}`, '', `*${formatPeriod(edu.dates)}*`, '')
    if (edu.description) push(edu.description, '')
    const activities = edu.activities.map(
      (activity) => messages.activities[activity as keyof typeof messages.activities],
    )
    push(`**Courses:** ${activities.join(', ')}`, '')
  }

  push('## Skills', '', skillNames.join(', '), '')
  if (staleSkillsNote) push(`*${staleSkillsNote.replace('*', '\\*')}*`, '')
  push('## Languages', '')
  push(...self.languages.map((language) => `- **${language.name}:** ${language.level}`), '')
  push('## Interests', '')
  push(`- **Professional:** ${interests(self.professionalInterests)}`)
  push(`- **Personal:** ${interests(self.personalInterests)}`, '')

  return lines.join('\n')
}

function tex(value: string): string {
  return value
    .replace(/\\/g, '\\textbackslash{}')
    .replace(/([&%$#_{}])/g, '\\$1')
    .replace(/~/g, '\\textasciitilde{}')
    .replace(/\^/g, '\\textasciicircum{}')
}

function texPeriod(dates: Period): string {
  return tex(formatPeriod(dates, 'LLL yyyy')).replace(' - ', ' -- ')
}

function texItems(items: string[]): string[] {
  return ['\\begin{itemize}', ...items.map((item) => `  \\item ${tex(item)}`), '\\end{itemize}']
}

function renderLatex(): string {
  const lines: string[] = []
  const push = (...values: string[]) => lines.push(...values)

  push(
    '% Generated by scripts/generate-resume.ts from src/data: do not edit by hand.',
    '\\documentclass{resume}',
    '',
    `\\hypersetup{pdftitle={${tex(fullName)} -- Resume}, pdfauthor={${tex(fullName)}}}`,
    '',
    '\\begin{document}',
    '',
    `\\resumeheader{${tex(self.firstName)}}{${tex(self.lastName.toUpperCase())}}{${tex(self.headline)}}{picture}`,
    `  {${tex(self.locations.join(' | '))}}{${tex(nationality)}}{${age}}`,
    `  {\\contact{\\faPhone}{${self.phone.href}}{${tex(self.phone.label)}}`,
    ...[self.email, ...self.links].map((link) => {
      const icon = link.href.startsWith('mailto:')
        ? '\\faEnvelope'
        : link.href.includes('linkedin')
          ? '\\faLinkedin'
          : link.href.includes('github.com')
            ? '\\faGithub'
            : '\\faGlobe'
      return `   \\contact{${icon}}{${link.href}}{${tex(link.label)}}`
    }),
    '  }',
    '',
    `\\summary{${tex(self.summary)}}`,
    '',
  )

  push('\\resumesection{Experience}', '')
  for (const xp of experience) {
    push(
      `\\experience{${tex(xp.company)}}{${tex(xp.title)}}{${tex(xp.location)}}{${texPeriod(xp.dates)}}`,
      `\\about{${tex(xp.about)}}`,
    )
    for (const stage of xp.stages.filter((stage) => !stage.hide)) {
      push(`\\stage{${tex(stage.name)}}{${texPeriod(stage.dates)}}`)
      if (stage.description) push(`\\stagedescription{${tex(stage.description)}}`)
      push(`\\stack{${tex(stage.skills.join(', '))}}`, ...texItems(stage.tasks))
    }
    push('')
  }

  push('\\resumesection{Personal Projects}', '')
  for (const project of projects) {
    const name = project.url ? `\\href{${project.url}}{${tex(project.name)}}` : tex(project.name)
    push(
      `\\project{${name}}{${texPeriod(project.dates)}}`,
      `\\stagedescription{${tex(project.about)}}`,
      `\\stack{${tex(project.skills.join(', '))}}`,
      ...texItems(project.tasks),
      '',
    )
  }

  push('\\resumesection{Education}', '')
  for (const edu of education) {
    const activities = edu.activities.map(
      (activity) => messages.activities[activity as keyof typeof messages.activities],
    )
    push(`\\education{${tex(edu.institution)}}{${tex(edu.degree)}}{${texPeriod(edu.dates)}}`)
    if (edu.description) push(`\\stagedescription{${tex(edu.description)}}`)
    push(`\\stack{${tex(activities.join(', '))}}`, '')
  }

  push(
    '\\resumesection{Skills, Languages \\& Interests}',
    '',
    '\\begin{facts}',
    `  \\fact{Skills}{${tex(skillNames.join(', '))}${staleSkillsNote ? `\\newline{\\footnotesize\\itshape\\color{muted}${tex(staleSkillsNote)}}` : ''}}`,
    `  \\fact{Languages}{${tex(self.languages.map((l) => `${l.name} (${l.level})`).join(', '))}}`,
    `  \\fact{Professional}{${tex(interests(self.professionalInterests))}}`,
    `  \\fact{Personal}{${tex(interests(self.personalInterests))}}`,
    '\\end{facts}',
    '',
    '\\end{document}',
    '',
  )

  return lines.join('\n')
}

for (const [path, content] of [
  [MARKDOWN_PATH, renderMarkdown()],
  [LATEX_PATH, renderLatex()],
] as const) {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, content)
  console.log(`Wrote ${path.replace(`${ROOT}/`, '')}`)
}
